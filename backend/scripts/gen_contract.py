"""Generate the API contract from the route registry and Pydantic models.

Outputs (both committed, both regenerated by CI to detect drift):
  contracts/openapi.json          OpenAPI 3.1 document
  contracts/api.gen.ts            TypeScript types + endpoint table used by front/

Usage:  python -m scripts.gen_contract [--check]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import typing
from pathlib import Path

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app import api, schemas, schemas_ai  # noqa: E402
import app.main  # noqa: E402,F401 — registers routes

REF = "#/components/schemas/{model}"


def _models() -> list[type[BaseModel]]:
    out = {}
    for module in (schemas, schemas_ai):
        for name in dir(module):
            obj = getattr(module, name)
            if isinstance(obj, type) and issubclass(obj, BaseModel) and obj not in (BaseModel, schemas.Model):
                out[obj.__name__] = obj
    return sorted(out.values(), key=lambda m: m.__name__)


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p.title() for p in rest)


def _response_schema(resp) -> tuple[dict, str]:
    if resp is None:
        return {}, "unknown"
    if typing.get_origin(resp) is list:
        inner = typing.get_args(resp)[0]
        return {"type": "array", "items": {"$ref": REF.format(model=inner.__name__)}}, f"{inner.__name__}[]"
    return {"$ref": REF.format(model=resp.__name__)}, resp.__name__


def build_openapi() -> dict:
    _, defs = models_json_schema([(m, "validation") for m in _models()], ref_template=REF)
    paths: dict[str, dict] = {}
    for spec in api.REGISTRY:
        op: dict = {"operationId": _camel(spec.handler.__name__), "summary": spec.summary, "tags": [spec.tag]}
        params = [{"name": p, "in": "path", "required": True, "schema": {"type": "string"}}
                  for p in re.findall(r"{(\w+)}", spec.path)]
        params += [{"name": q, "in": "query", "required": False, "description": d, "schema": {"type": "string"}}
                   for q, d in spec.query.items()]
        if spec.multipart:
            params.append({"name": "Idempotency-Key", "in": "header", "required": False,
                           "description": "Replays the first response for this user and application for 24 hours.",
                           "schema": {"type": "string", "maxLength": 200}})
        if params:
            op["parameters"] = params
        if spec.body is not None:
            op["requestBody"] = {"required": True, "content": {"application/json": {
                "schema": {"$ref": REF.format(model=spec.body.__name__)}}}}
        if spec.multipart:
            op["requestBody"] = {"required": True, "content": {"multipart/form-data": {"schema": {
                "type": "object", "required": ["file", "doc_type"],
                "properties": {"file": {"type": "string", "format": "binary"},
                               "doc_type": {"$ref": REF.format(model="DocumentOut") + "/properties/doc_type"}}}}}}
        schema, _ = _response_schema(spec.response)
        content = {spec.raw if isinstance(spec.raw, str) else "image/png": {"schema": {"type": "string", "format": "binary"}}} if spec.raw else \
            {"application/json": {"schema": schema or {"type": "object"}}}
        op["responses"] = {str(spec.status): {"description": "Success", "content": content},
                           "default": {"description": "Error", "content": {"application/json": {
                               "schema": {"$ref": REF.format(model="ErrorOut")}}}}}
        if spec.method == 'GET' and spec.path == '/api/v1/applications':
            op['responses']['200']['headers'] = {'X-Total-Count': {
                'description': 'Matching applications before pagination.', 'schema': {'type': 'integer'}}}
        if spec.path == '/api/v1/metrics':
            op['security'] = [{'metrics': []}]
        elif spec.public:
            op["security"] = []
        else:
            op["x-roles"] = list(spec.roles) if spec.roles else ["any authenticated"]
        paths.setdefault(spec.path, {})[spec.method.lower()] = op
    return {
        "openapi": "3.1.0",
        "info": {"title": "PRAMAAN API", "version": "1.0.0",
                 "description": "Decision-support API for AICTE application validation (SIH26261). All findings are "
                                "advisory; the API cannot approve, reject or declare a document forged."},
        "servers": [{"url": "/"}],
        "paths": paths,
        "components": {"schemas": defs["$defs"], "securitySchemes": {
            "session": {"type": "apiKey", "in": "cookie", "name": api.SESSION_COOKIE},
            "bearer": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT"},
            "metrics": {"type": "http", "scheme": "bearer", "description": "Separate METRICS_TOKEN; off when unset."}}},
        "security": [{"session": []}, {"bearer": []}],
    }


def _ts(schema: dict, indent: str = "  ") -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts(s, indent) for s in schema["anyOf"]))
    t = schema.get("type")
    if t == "array":
        inner = _ts(schema.get("items", {}), indent)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "properties" in schema:
            return _interface_body(schema, indent)
        ap = schema.get("additionalProperties")
        return f"Record<string, {_ts(ap, indent) if isinstance(ap, dict) and ap else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def _interface_body(schema: dict, indent: str) -> str:
    req = set(schema.get("required", []))
    lines = ["{"]
    for name, prop in schema.get("properties", {}).items():
        opt = "" if name in req else "?"
        lines.append(f"{indent}{name}{opt}: {_ts(prop, indent + '  ')};")
    if schema.get("additionalProperties") is True:
        lines.append(f"{indent}[key: string]: unknown;")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


def build_ts(openapi: dict) -> str:
    out = ["// GENERATED by backend/scripts/gen_contract.py — do not edit by hand.",
           "// Source of truth: backend/app/schemas.py and the route registry in backend/app/api.py.", ""]
    seen: set[str] = set()
    for module in (schemas, schemas_ai):
        for name in dir(module):
            obj = getattr(module, name)
            if typing.get_origin(obj) is typing.Literal and name not in seen:
                seen.add(name)
                values = typing.get_args(obj)
                out.append(f"export type {name} = {' | '.join(json.dumps(v) for v in values)};")
                out.append(f"export const {re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()}_VALUES = "
                           f"{json.dumps(list(values))} as const;")
    out.append("")
    for name, schema in openapi["components"]["schemas"].items():
        out.append(f"export interface {name} {_interface_body(schema, '  ')}")
        out.append("")
    out.append("export const endpoints = {")
    resp_lines = []
    for path, methods in openapi["paths"].items():
        for method, op in methods.items():
            spec = next(s for s in api.REGISTRY if s.path == path and s.method.lower() == method)
            _, ts_resp = _response_schema(spec.response)
            body = spec.body.__name__ if spec.body else ("FormData" if spec.multipart else "undefined")
            out.append(f"  {op['operationId']}: {{ method: {json.dumps(method.upper())}, path: {json.dumps(path)} }},")
            resp_lines.append(f"  {op['operationId']}: {{ response: {ts_resp if not spec.raw else 'Blob'}; body: {body} }};")
    out.append("} as const;")
    out.append("")
    out.append("export interface EndpointTypes {")
    out.extend(resp_lines)
    out.append("}")
    out.append("export type EndpointName = keyof typeof endpoints;")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if committed files differ from generated output")
    args = ap.parse_args()
    openapi = build_openapi()
    files = {ROOT / "contracts" / "openapi.json": json.dumps(openapi, indent=2) + "\n",
             ROOT / "contracts" / "api.gen.ts": build_ts(openapi)}
    stale = []
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("Contract out of date:", *stale, sep="\n  ")
        sys.exit(1)
    print(f"{len(api.REGISTRY)} operations, {len(openapi['components']['schemas'])} schemas "
          f"{'verified' if args.check else 'written'}")


if __name__ == "__main__":
    main()
